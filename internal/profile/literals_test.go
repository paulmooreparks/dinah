package profile

import (
	"go/ast"
	"go/parser"
	"go/token"
	"io/fs"
	"path/filepath"
	"strings"
	"testing"
)

// wireLiterals are the string literals that keep Dinah's name whatever the
// profile says, because they are written and read back or stored: the chat
// and turn markers, the applet context and handoff headings, the sender name
// the bus stores for its own reports, the ACP client's title, and the text
// saved copies keep and are compared with. The generated bridge script's
// comment is not shown to anybody. Each is matched by a part of it.
var wireLiterals = []string{
	`[Dinah chat: `,
	`[Dinah turn: `,
	`\[Dinah chat: `,
	`\[Dinah turn: `,
	`[Dinah Applet Context]`,
	`"[Dinah "`, // where an injected block begins in a title (bus.CleanTitle)
	`[Dinah Conversation Handoff]`,
	`from_name = 'Dinah'`,
	`messages outside Dinah's saved transcript`,
	`// Generated by Dinah's bridge`,
}

// TestNoProductNameOutsideTheProfile checks that no Go string literal in the
// programs and their packages spells Dinah's name, apart from the profile
// and the wire literals above, so that a new message cannot bypass the
// profile by accident. The ACP client's title is a literal "Dinah" given
// with the name "dinah", and is matched as such.
func TestNoProductNameOutsideTheProfile(t *testing.T) {
	root := filepath.Join("..", "..")
	var found []string
	for _, dir := range []string{"cmd", "internal"} {
		err := filepath.WalkDir(filepath.Join(root, dir), func(path string, d fs.DirEntry, err error) error {
			if err != nil {
				return err
			}
			if d.IsDir() {
				if d.Name() == "frontend" || d.Name() == "static" || filepath.Base(path) == "profile" {
					return filepath.SkipDir
				}
				return nil
			}
			if !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") {
				return nil
			}
			fset := token.NewFileSet()
			file, err := parser.ParseFile(fset, path, nil, parser.SkipObjectResolution)
			if err != nil {
				return err
			}
			ast.Inspect(file, func(n ast.Node) bool {
				if kv, ok := n.(*ast.CompositeLit); ok && acpClientInfo(kv) {
					return false
				}
				lit, ok := n.(*ast.BasicLit)
				if !ok || lit.Kind != token.STRING || !strings.Contains(lit.Value, "Dinah") {
					return true
				}
				for _, w := range wireLiterals {
					if strings.Contains(lit.Value, w) {
						return true
					}
				}
				found = append(found, fset.Position(lit.Pos()).String()+": "+lit.Value)
				return true
			})
			return nil
		})
		if err != nil {
			t.Fatal(err)
		}
	}
	for _, f := range found {
		t.Errorf("the product's name is spelled outside the profile: %s", f)
	}
}

// acpClientInfo says whether c is an ACP Implementation literal whose Name
// is "dinah". Its title stays "Dinah" on the wire.
func acpClientInfo(c *ast.CompositeLit) bool {
	sel, ok := c.Type.(*ast.SelectorExpr)
	if !ok || sel.Sel.Name != "Implementation" {
		return false
	}
	for _, e := range c.Elts {
		kv, ok := e.(*ast.KeyValueExpr)
		if !ok {
			continue
		}
		if key, ok := kv.Key.(*ast.Ident); ok && key.Name == "Name" {
			if v, ok := kv.Value.(*ast.BasicLit); ok && v.Value == `"dinah"` {
				return true
			}
		}
	}
	return false
}
