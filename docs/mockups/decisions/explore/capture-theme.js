// Writes the palette the real window applies through appearance.js, light and
// dark, as clear-chime-tokens.css for the mockup page.
//   pwsh scripts/with-test-lock.ps1 node docs/mockups/decisions/explore/capture-theme.js
const path = require('path'), fs = require('fs');
const E2E = path.join(__dirname, '..', '..', '..', '..', 'cmd', 'dinah-desktop', 'frontend', 'e2e');
const { launch } = require(path.join(E2E, 'lib', 'page'));
(async () => {
  const t = await launch({ viewport: { width: 1440, height: 1000 }, ready: 'workbench' });
  const out = [];
  try {
    for (const mode of ['light', 'dark']) {
      await t.page.evaluate(m => window.pudlSetTheme ? window.pudlSetTheme(m) : document.documentElement.setAttribute('data-theme', m), mode);
      await t.page.emulateMedia({ colorScheme: mode });
      await t.page.evaluate(m => { if (window.dinahAppearance && window.dinahAppearance.setMode) return window.dinahAppearance.setMode(m); }, mode).catch(() => {});
      await t.page.waitForTimeout(400);
      const info = await t.page.evaluate(() => {
        const root = document.documentElement, style = root.style, vars = [];
        for (let i = 0; i < style.length; i++) { const name = style[i]; if (name.startsWith('--')) vars.push(name + ': ' + style.getPropertyValue(name).trim() + ';'); }
        return { theme: root.getAttribute('data-theme'), skin: root.getAttribute('data-skin'), font: style.getPropertyValue('font-family'), vars };
      });
      console.log(mode, info.theme, info.skin, info.vars.length);
      out.push('/* ' + mode + ': data-theme ' + info.theme + ', skin ' + info.skin + ' */\n:root[data-theme="' + mode + '"] {\n  ' + info.vars.join('\n  ') + '\n}');
    }
  } finally { await t.close(); }
  fs.writeFileSync(path.join(__dirname, '..', 'clear-chime-tokens.css'), '/* Generated by explore/capture-theme.js from the real window: the inline palette appearance.js applies. */\n' + out.join('\n\n') + '\n');
})().catch(e => { console.error(e); process.exitCode = 1; });
